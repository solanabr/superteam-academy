// Start, stop and wipe the local Supabase stack for walks.
//
// The stack runs from a generated working directory (apps/web/.walk/supabase):
// a copy of the repo's supabase/config.toml with the walk project id and ports,
// and a copy of supabase/migrations. The repo's own files are not changed.

import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import {
  APP_URL,
  ENV_FILE,
  PORTS,
  PROJECT_ID,
  REPO_ROOT,
  SUPABASE_URL,
  WALK_DIR,
  fail,
  supabase,
} from "./lib.mjs";

const REPO_SUPABASE = join(REPO_ROOT, "supabase");
const WORK_SUPABASE = join(WALK_DIR, "supabase");

// Services a walk does not need. Storage stays on: the migrations write to the
// storage schema that the storage service creates.
const EXCLUDED_SERVICES = [
  "realtime",
  "imgproxy",
  "mailpit",
  "studio",
  "postgres-meta",
  "edge-runtime",
  "logflare",
  "vector",
  "supavisor",
];

const SECTION_PORTS = {
  api: PORTS.api,
  db: PORTS.db,
  "db.pooler": PORTS.pooler,
  studio: PORTS.studio,
  inbucket: PORTS.inbucket,
};
const SECTIONS_OFF = new Set(["studio", "inbucket", "db.pooler", "analytics"]);
const REQUIRED_KEYS = [
  ".project_id",
  "api.port",
  "db.port",
  "db.shadow_port",
  "studio.port",
  "inbucket.port",
  "auth.site_url",
];
const APPENDED = `
[realtime]
enabled = false

[edge_runtime]
enabled = false

[storage]
enabled = true

[storage.image_transformation]
enabled = false

[db.seed]
enabled = false
`;

/** The repo's config with the walk project id, ports and app URL. */
export function walkConfig(source) {
  let section = "";
  const replaced = new Set();
  const lines = source.split("\n").map((line) => {
    const header = /^\[(.+)\]$/.exec(line.trim());
    if (header) {
      section = header[1];
      if (APPENDED.includes(`[${section}]`)) {
        fail(
          `supabase/config.toml now has [${section}]: update walk/stack.mjs`
        );
      }
      return line;
    }
    const key = /^([a-z_]+)\s*=/.exec(line.trim())?.[1];
    if (!key) return line;
    const set = (value) => {
      replaced.add(`${section}.${key}`);
      return `${key} = ${value}`;
    };
    if (section === "" && key === "project_id") return set(`"${PROJECT_ID}"`);
    if (key === "port" && section in SECTION_PORTS) {
      return set(SECTION_PORTS[section]);
    }
    if (section === "db" && key === "shadow_port") return set(PORTS.shadowDb);
    if (key === "enabled" && SECTIONS_OFF.has(section)) return set("false");
    if (section === "auth" && key === "site_url") return set(`"${APP_URL}"`);
    if (section === "auth" && key === "additional_redirect_urls") {
      return set(`["${APP_URL}/api/auth/callback"]`);
    }
    return line;
  });
  const missing = REQUIRED_KEYS.filter((key) => !replaced.has(key));
  if (missing.length > 0) {
    fail(
      `supabase/config.toml has no ${missing.join(", ")}: update walk/stack.mjs`
    );
  }
  return `# Generated by apps/web/walk/stack.mjs. Do not edit.\n${lines.join("\n")}${APPENDED}`;
}

function prepareWorkdir() {
  rmSync(WORK_SUPABASE, { recursive: true, force: true });
  mkdirSync(join(WORK_SUPABASE, "migrations"), { recursive: true });
  writeFileSync(
    join(WORK_SUPABASE, "config.toml"),
    walkConfig(readFileSync(join(REPO_SUPABASE, "config.toml"), "utf8"))
  );
  // Only the files the CLI applies. The .backfill, .verify and .rollback files
  // next to some migrations are operator steps, not migrations.
  const migrations = readdirSync(join(REPO_SUPABASE, "migrations")).filter(
    (name) => /^\d{14}_.+\.sql$/.test(name)
  );
  for (const name of migrations) {
    copyFileSync(
      join(REPO_SUPABASE, "migrations", name),
      join(WORK_SUPABASE, "migrations", name)
    );
  }
  return migrations.length;
}

function requireDocker() {
  const docker = spawnSync("docker", ["info"], { stdio: "ignore" });
  if (docker.status !== 0) {
    fail(
      "Docker is not running. Start your Docker runtime first (colima start)."
    );
  }
}

export function up() {
  requireDocker();
  const count = prepareWorkdir();
  console.log(`[walk] ${count} migrations copied to apps/web/.walk/supabase`);
  // The CLI ends with a table of the stack's keys on stdout. Keep it out of
  // the terminal and of session logs; `walk env` reads the keys when needed.
  const start = supabase(["start", "-x", EXCLUDED_SERVICES.join(",")], {
    hideStdout: true,
  });
  if (start.status !== 0) fail("supabase start failed (see above)");
  // A stack that was stopped and started again keeps its data. Apply what the
  // current branch added since.
  const migrate = supabase(["migration", "up", "--local"]);
  if (migrate.status !== 0) {
    fail(
      "supabase migration up failed (see above). When the stack's schema is from " +
        "another branch, run: pnpm --filter web walk wipe, then up"
    );
  }
}

export function down() {
  requireDocker();
  mkdirSync(WALK_DIR, { recursive: true });
  const stop = supabase(["stop", "--project-id", PROJECT_ID]);
  if (stop.status !== 0) fail("supabase stop failed (see above)");
}

export function wipe() {
  requireDocker();
  mkdirSync(WALK_DIR, { recursive: true });
  const stop = supabase(["stop", "--project-id", PROJECT_ID, "--no-backup"]);
  if (stop.status !== 0) fail("supabase stop failed (see above)");
  rmSync(WALK_DIR, { recursive: true, force: true });
  rmSync(ENV_FILE, { force: true });
  console.log(
    "[walk] data volumes, apps/web/.walk and apps/web/.env.walk removed"
  );
}

/** Asks Docker, not the working directory, so it is right in any worktree. */
export function status() {
  requireDocker();
  const ps = spawnSync(
    "docker",
    ["ps", "-q", "--filter", `name=^supabase_db_${PROJECT_ID}$`],
    { encoding: "utf8" }
  );
  console.log(
    ps.stdout.trim()
      ? `[walk] stack is up on ${SUPABASE_URL}`
      : "[walk] stack is not running"
  );
}
