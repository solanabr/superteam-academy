// Write apps/web/.env.walk for the running walk stack.
//
// Every value is either read from the local stack, a public devnet value, or
// made here. Signers are new throwaway keypairs: they hold no SOL and are not
// the program's signers, so on-chain writes fail. Reporting and third-party
// keys are blank, so nothing leaves the machine except devnet RPC reads.

import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { Keypair } from "@solana/web3.js";
import {
  APP_URL,
  BUILD_STUB_URL,
  DEVNET_RPC,
  ENV_FILE,
  requireStack,
} from "./lib.mjs";

// The devnet program id from docs/DEPLOY-PROGRAM.md.
const DEVNET_PROGRAM_ID = "Dsro2Cd9Mhgk8L71imh3LLPwYU5PU8hvBY5HEcPrcx5u";

const keypair = () => JSON.stringify(Array.from(Keypair.generate().secretKey));
const secret = () => randomBytes(24).toString("base64url");

const BLANK = [
  "NEXT_PUBLIC_XP_MINT_ADDRESS",
  "NEXT_PUBLIC_DYNAMIC_ENVIRONMENT_ID",
  "NEXT_PUBLIC_GA4_MEASUREMENT_ID",
  "NEXT_PUBLIC_POSTHOG_KEY",
  "NEXT_PUBLIC_POSTHOG_HOST",
  "NEXT_PUBLIC_SENTRY_DSN",
  "SENTRY_ORG",
  "SENTRY_PROJECT",
  "SENTRY_AUTH_TOKEN",
  "GEMINI_API_KEY",
  "HELIUS_API_KEY",
  "ARWEAVE_UPLOADER_SECRET",
  "GITHUB_TOKEN",
  "MODERATION_WEBHOOK_URL",
  "RESEND_API_KEY",
  "EMAIL_FROM",
  "RUST_PLAYGROUND_URL",
];

export function writeEnv() {
  const stack = requireStack();
  const values = {
    NEXT_PUBLIC_SUPABASE_URL: stack.url,
    NEXT_PUBLIC_SUPABASE_ANON_KEY: stack.anonKey,
    SUPABASE_SERVICE_ROLE_KEY: stack.serviceRoleKey,
    NEXT_PUBLIC_SOLANA_RPC_URL: DEVNET_RPC,
    SOLANA_RPC_URL: DEVNET_RPC,
    NEXT_PUBLIC_SOLANA_NETWORK: "devnet",
    NEXT_PUBLIC_LEARNER_DEPLOY_ENABLED: "true",
    NEXT_PUBLIC_PROGRAM_ID: DEVNET_PROGRAM_ID,
    NEXT_PUBLIC_APP_URL: APP_URL,
    BUILD_SERVER_URL: BUILD_STUB_URL,
    BUILD_SERVER_API_KEY: secret(),
    BACKEND_SIGNER_SECRET: keypair(),
    PROGRAM_AUTHORITY_SECRET: keypair(),
    XP_MINT_AUTHORITY_SECRET: keypair(),
    SPONSOR_SECRET: keypair(),
    AI_PARTNER_SEAL_SECRET: secret(),
    HELIUS_WEBHOOK_SECRET: secret(),
    CRON_SECRET: secret(),
    TEACH_PREVIEW_PASSWORD: secret(),
    ...Object.fromEntries(BLANK.map((name) => [name, ""])),
  };
  const lines = [
    "# Generated by apps/web/walk/env.mjs for the local walk stack. Do not commit.",
    ...Object.entries(values).map(([name, value]) => `${name}=${value}`),
  ];
  writeFileSync(ENV_FILE, `${lines.join("\n")}\n`, { mode: 0o600 });
  console.log("[walk] wrote apps/web/.env.walk");
}
